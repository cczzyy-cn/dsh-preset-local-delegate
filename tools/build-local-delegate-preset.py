#!/usr/bin/env python3
"""Build the `local-delegate` preset bundle: the shipped `standard` preset + local delegation.

WHY A GENERATOR AND NOT A HAND-EDITED FILE. The claim this preset makes is "the shipped
`standard` preset, VERBATIM, plus one added capability". A hand-copied list drifts silently the
first time the harness is upgraded, and the drift is invisible in review because the file still
looks like a preset. Here the base list is read out of this build's own app.asar at build time,
so `cordis.patch.yml` can always be regenerated and diffed against the shipped definition.

What is added, and nothing else:

    - id: local-delegate
      name: dsh-preset-local-delegate/local-delegate.mjs

which registers `verify_task`, `delegate_batch`, and the routing guidance section.

Usage:
    python tools/build-local-delegate-preset.py [--check]

    --check   do not write; fail if cordis.patch.yml is not what would be generated
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BUNDLE = REPO
PKG_NAME = "dsh-preset-local-delegate"

PRESET_ID = "local-delegate"
PRESET_NAME = "Local Delegate"
PRESET_ORDER = 3
PRESET_DESC = (
    "The shipped `standard` preset verbatim, plus one capability: subtasks whose answer a machine "
    "can check are delegated to the local Strata engine as a subagent (0 API tokens), gated by a "
    "deterministic verifier (verify_task), and escalated to DeepSeek when the gate fails. Multi-step "
    "reasoning, anything not deterministically verifiable, and the final user-facing wording stay on DeepSeek."
)

# the added row, appended AFTER the shipped list: it consumes `tools`, `systemPrompt` and the
# host `subagents` singleton, all of which the shipped rows above it establish.
ADDED_ROWS = f"""\
          # ── the one thing this preset adds ───────────────────────────────────────────
          #
          # Gated local delegation. `verify_task` + `delegate_batch` + the routing guide.
          # Everything above this line is the shipped `standard` preset, byte for byte.
          - id: local-delegate
            name: {PKG_NAME}/local-delegate.mjs
            config: {{}}
"""

HEADER = f"""\
# {PKG_NAME} — the `{PRESET_ID}` agent preset.
#
# This file is an AGENT-PLANE composition: it is mounted under one agent's scope context, so
# every tool and prompt section it registers belongs to that session alone. The host
# composition keeps the registries themselves, the sandbox and approval stack, persistence,
# and the model route.
#
# GENERATED by tools/build-local-delegate-preset.py — edit that, not this.
#
# The `plugins:` list below is the SHIPPED `standard` preset's list read out of this build's
# app.asar, verbatim and in its original order, followed by the one row this preset adds. To see
# the difference, regenerate and compare against:
#
#     python tools/dump-shipped-preset.py standard --body-only
#
# A service row here MUST sit inside a group carrying an `isolate` realm; the shipped rows
# already do. The added row provides no service (it only registers tools and a prompt section),
# so it needs no realm and sits at the top level.
"""


def load_dumper():
    """Import tools/dump-shipped-preset.py by path — the filename is not a valid module name."""
    spec = importlib.util.spec_from_file_location(
        "dsh_dump_shipped_preset", REPO / "tools" / "dump-shipped-preset.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def shipped_standard_body(asar: str | None) -> str:
    """The `standard` preset's plugin list, dedented back to column 0."""
    dumper = load_dumper()
    text = (Path(asar) if asar else dumper.DEFAULT_ASAR).read_bytes().decode("utf-8", "replace")
    blocks = dumper.blocks_for(text, "standard")
    if not blocks:
        raise SystemExit("could not find the shipped `standard` preset in app.asar")
    _, best = max(blocks, key=lambda p: dumper.plugin_rows(p[1]))
    body = dumper.dedent_body(best)
    rows = dumper.plugin_rows(body)
    if rows < 20:
        raise SystemExit(f"shipped `standard` body has only {rows} rows — refusing to build from it")
    return body


def indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join((pad + ln) if ln.strip() else ln for ln in text.splitlines())


# The engine facts this build's preset describes. ONE file, so a model swap cannot half-happen: the
# compaction policy below, the module's default route and the README all name the same id, and
# `scripts/check-docs.mjs` / `scripts/doctor.mjs` fail when they disagree.
ENGINE_PROFILE = REPO / "engine-profile.json"


def engine() -> dict:
    try:
        return json.loads(ENGINE_PROFILE.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise SystemExit(f"no {ENGINE_PROFILE.name} beside the preset — it is the single source for "
                         f"the model id, context window and sampling facts")


# The ONE shipped row this deployment configures instead of copying verbatim: the condensation
# backend. It is configured here because nothing else can reach it — the preset registry only lets a
# patch target the PRESET row's id ("A new preset or an override of a shipped one is a bundle patch"),
# so a row *inside* the preset is configurable only in this generated list.
#
# Why this policy: the trigger is `floor(min(W x thresholdRatio, W - O - headroomTokens))` with the
# request output cap O (the provider row's maxTokens) and the headroom B. For the local route
# (W = engine-profile.maxContext, O = engine-profile.maxTokens) the default B = 65536 made
# `W - O - B` the binding term, so a session compacted at 131072 tokens instead of at 80% of the
# window. B = 0 removes that term, and the 0.8 fraction decides: 209715 tokens. `maxTokens` here is
# the SUMMARY cap, and zero headroom requires an explicit positive one. Only the local route is
# overridden, so DeepSeek keeps its own policy.
COMPACTION_CONFIG = """\
      config:
        modelPolicies:
          - provider: {provider}
            model: {model}
            thresholdRatio: 0.8
            headroomTokens: 0
            maxTokens: 4096
"""


# Prompt variables this build's loop registers for a persona TEMPLATE. `prefix` and `suffix` are not
# plain text: the persona row hands them to the prompt registry, which resolves every complete
# `{{...}}` group STRICTLY, and an unknown name fails prompt ASSEMBLY — before any model request, so
# every session on the preset dies with no transcript of its own. Measured 2026-10-18 on the desktop
# 0.2.0-rc.2 build, after the `standard` preset's old suffix came along with the base list verbatim:
#
#   unknown prompt variable "{{cwd}}" in section "deployment:persona-suffix";
#   registered variables: provider, model
#
# `cwd` is a leftover that the old shipped preset carried as `suffix: Your working directory is
# {{cwd}}.`. The current build dropped it because the working directory now arrives as literal user
# context (the working-directory service), not as a template variable — so the clause is both
# unrenderable and redundant. Extending this set is only correct after checking the running build's
# own registry: `tools/asar-read.py --grep 'registered variables'`.
REGISTERED_PROMPT_VARIABLES = frozenset({"provider", "model"})


def check_prompt_variables(patch: str) -> list[str]:
    """Every `{{var}}` the patch emits must be one the persona registry can resolve.

    The base list is copied verbatim, so a shipped preset that still carries a dead variable would
    be reproduced silently; this turns that into a build failure that names the line and the rule.
    """
    import re

    problems: list[str] = []
    registered = ", ".join(sorted(REGISTERED_PROMPT_VARIABLES))
    for m in re.finditer(r"\{\{\s*([A-Za-z0-9_.:-]+)\s*\}\}", patch):
        name = m.group(1)
        if name in REGISTERED_PROMPT_VARIABLES:
            continue
        line_no = patch.count("\n", 0, m.start()) + 1
        problems.append(
            f"line {line_no}: the patch interpolates {{{{ {name} }}}}, which this build does not "
            f"register for persona templates (registered: {registered}). Prompt assembly fails "
            f"before any model request — measured 2026-10-18: \"unknown prompt variable\" in "
            f"section \"deployment:persona-suffix\". Drop the clause, or extend "
            f"REGISTERED_PROMPT_VARIABLES after checking the running build's own registry."
        )
    return problems


def configure_compaction(body: str) -> str:
    """Append this deployment's condensation policy to the shipped `compaction-basic` row.

    Fails loudly when the shipped row moves, is renamed or is duplicated: emitting no config would
    silently leave every session on the default trigger, which is exactly the bug being fixed here.
    """
    lines = body.splitlines()
    hits = [i for i, ln in enumerate(lines) if ln.strip() == "- id: compaction-basic"]
    if len(hits) != 1:
        raise SystemExit(f"expected exactly one `- id: compaction-basic` row in the shipped preset, "
                         f"found {len(hits)} — the shipped list moved; update this function")
    i = hits[0]
    if not lines[i + 1].strip().startswith("name: '@deepseek-ai/dsh-compaction-basic'"):
        raise SystemExit(f"the `compaction-basic` row is not followed by its name line: {lines[i + 1]!r}")
    facts = engine()
    block = COMPACTION_CONFIG.format(provider=facts["provider"], model=facts["model"])
    lines[i + 2:i + 2] = block.rstrip("\n").splitlines()
    return "\n".join(lines)


def build(asar: str | None) -> str:
    body = configure_compaction(shipped_standard_body(asar))
    decl = [
        "- insert:",
        f"    - id: preset-{PRESET_ID}",
        "      name: '@deepseek-ai/dsh-agent-preset'",
        "      config:",
        f"        id: {PRESET_ID}",
        f"        name: {json.dumps(PRESET_NAME, ensure_ascii=False)}",
        f"        description: {json.dumps(PRESET_DESC, ensure_ascii=False)}",
        f"        order: {PRESET_ORDER}",
        "        plugins:",
    ]
    # `plugins:` sits at indent 8, so its items must go deeper or YAML reads the key as null.
    patch = HEADER + "\n".join(decl) + "\n" + indent(body, 10).rstrip("\n") + "\n" + ADDED_ROWS
    return patch


def self_check(patch: str) -> list[str]:
    """Parse the generated patch and assert every row is complete.

    Indentation is the whole game: a row emitted at the wrong depth becomes a sibling field,
    loses its own `id`, and silently changes the preset.
    """
    import yaml

    class _L(yaml.SafeLoader):
        pass

    _L.add_constructor("tag:yaml.org,2002:js", lambda l, n: l.construct_scalar(n))
    try:
        doc = yaml.load(patch, Loader=_L)
    except Exception as e:                                   # noqa: BLE001
        return [f"patch is not valid YAML: {e}"]

    if not isinstance(doc, list) or not doc or "insert" not in doc[0]:
        return ["patch is not a top-level list whose first entry has `insert:`"]
    cfg = (doc[0]["insert"][0].get("config") or {})
    plugins = cfg.get("plugins")
    if not isinstance(plugins, list) or not plugins:
        return ["`config.plugins` did not parse as a non-empty list"]

    problems: list[str] = []

    def walk(rows, depth=0):
        for r in rows:
            if not isinstance(r, dict):
                problems.append(f"row is not a mapping: {r!r}")
                continue
            if "name" not in r:
                problems.append(f"row id={r.get('id')!r} has no `name`")
            if "id" not in r:
                problems.append(f"row name={r.get('name')!r} has no `id`")
            grp = r.get("config")
            if isinstance(grp, list):
                walk(grp, depth + 1)

    walk(plugins)
    names = [r.get("name") for r in plugins if isinstance(r, dict)]
    if f"{PKG_NAME}/local-delegate.mjs" not in names:
        problems.append("the added local-delegate row is missing from the plugin list")
    return problems


def self_test() -> int:
    """Pin the dead-variable guard: a `{{cwd}}` suffix must be rejected, a clean patch accepted.

    Measured 2026-10-18: the guard is what stands between a shipped-preset leftover and every
    session on this preset failing prompt assembly, so it gets its own case rather than being
    trusted. Run with `--selftest`.
    """
    dead = ("              prefix: You are a coding agent powered by the {{model}} model.\n"
            "              suffix: Your working directory is {{cwd}}.\n")
    live = "              prefix: You are a coding agent powered by the {{model}} model.\n"

    failures: list[str] = []
    rejected = check_prompt_variables(dead)
    if len(rejected) != 1 or "cwd" not in rejected[0]:
        failures.append(f"a {{cwd}} suffix was not rejected exactly once: {rejected!r}")
    if check_prompt_variables(live):
        failures.append(f"a patch with only {{{{model}}}} was rejected: "
                        f"{check_prompt_variables(live)!r}")
    if check_prompt_variables("{{provider}} and {{model}} are fine"):
        failures.append("the two registered variables were rejected")
    if failures:
        for f in failures:
            print(f"  FAIL  {f}", file=sys.stderr)
        return 1
    print("ok   a {{cwd}} persona suffix is rejected, naming the variable")
    print("ok   {{provider}} and {{model}} pass")
    print("\n3 passed, 0 failed")
    return 0


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass

    ap = argparse.ArgumentParser()
    ap.add_argument("--asar", default="")
    ap.add_argument("--check", action="store_true", help="do not write; fail if the file is stale")
    ap.add_argument("--selftest", action="store_true",
                    help="check the dead-prompt-variable guard itself, then exit")
    a = ap.parse_args()

    if a.selftest:
        return self_test()

    patch = build(a.asar or None)
    problems = self_check(patch)
    if problems:
        for p in problems:
            print(f"  !! {p}", file=sys.stderr)
        raise SystemExit("refusing to write a structurally invalid patch (see above)")

    unresolved = check_prompt_variables(patch)
    if unresolved:
        for p in unresolved:
            print(f"  !! {p}", file=sys.stderr)
        raise SystemExit("refusing to write a patch whose persona templates cannot resolve "
                         "(a dead {{variable}} breaks every session on this preset)")

    out = BUNDLE / "cordis.patch.yml"
    rows = patch.count("\n          - id:") + patch.count("\n            - id:")
    if a.check:
        cur = out.read_text(encoding="utf-8") if out.exists() else ""
        if cur == patch:
            print(f"{out} is up to date ({len(patch)} B)")
            return 0
        print(f"!! {out} is STALE: regenerate with tools/build-local-delegate-preset.py", file=sys.stderr)
        return 1

    BUNDLE.mkdir(parents=True, exist_ok=True)
    out.write_text(patch, encoding="utf-8")
    print(f"wrote {out}")
    print(f"  preset id   : {PRESET_ID}")
    print(f"  base body   : the shipped `standard` preset, verbatim ({rows} plugin rows)")
    print(f"  added row   : {PKG_NAME}/local-delegate.mjs")
    print(f"  bytes       : {len(patch)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
